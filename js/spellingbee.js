/* ============================================================
   Spelling Bee: hear a word, spell it.
   Word packs live in js/bee-words/level-N.js (generated by
   tools/build_bee_words.py) and are loaded one level at a time.
   Each word: { w, p?, d?, s, a?, h? }
     w word · p part of speech · d definition · s example sentence
     a US spellings (marked wrong, with a note) · h sound-alike words
   Runs on game-engine.js.
   ============================================================ */

(function () {
	const esc = Widgets.esc;

	const LEVELS = [
		{ name: "Starter", blurb: "Short, everyday words" },
		{ name: "Everyday", blurb: "Common words you read often" },
		{ name: "Confident", blurb: "Longer words and patterns" },
		{ name: "Tricky", blurb: "Silent letters, doubles and more" },
		{ name: "Advanced", blurb: "Longer, less common words" },
		{ name: "Expert", blurb: "Hard words for strong spellers" },
		{ name: "Champion", blurb: "The toughest words in the bee" }
	];

	/* ---------- Word packs ---------- */

	const packs = {};
	function loadLevel(n) {
		window.BEE_WORDS = window.BEE_WORDS || {};
		if (window.BEE_WORDS[n]) return Promise.resolve(window.BEE_WORDS[n]);
		if (!packs[n]) {
			// A script tag rather than fetch() so the page also works when
			// opened straight from disk (file://).
			packs[n] = new Promise((resolve, reject) => {
				const s = document.createElement("script");
				s.src = `./js/bee-words/level-${n}.js`;
				s.onload = () => window.BEE_WORDS[n] ? resolve(window.BEE_WORDS[n]) : reject(new Error("empty pack"));
				s.onerror = () => { delete packs[n]; reject(new Error("load failed")); };
				document.head.appendChild(s);
			});
		}
		return packs[n];
	}

	/* Words in each pack run easiest to hardest. Progress through a level
	   slides a window along the pack, so words get harder within a level
	   as well as between levels. */
	function next(level, step, { used, mastered }) {
		const list = window.BEE_WORDS[level];
		const n = list.length;
		const parts = LevelGame.TO_LEVEL_UP;
		const start = Math.floor((step / parts) * n);
		const windowed = list.slice(start, start + Math.ceil(n / parts));

		const fresh = e => !used.has(e.w);
		let pool = windowed.filter(e => fresh(e) && !mastered.has(e.w));
		if (!pool.length) pool = list.filter(e => fresh(e) && !mastered.has(e.w));
		if (!pool.length) pool = list.filter(fresh);
		if (!pool.length) pool = windowed;      // spelled the whole level this session
		const entry = Rand.pick(pool);
		return { id: entry.w, entry };
	}

	/* ---------- Helpers ---------- */

	const norm = s => (s || "").trim().toLowerCase().replace(/[‘’]/g, "'").replace(/\s+/g, " ");

	// Hide the answer (and its US spelling) wherever it appears in a clue.
	function masked(text, entry) {
		const forms = [entry.w].concat(entry.a || []);
		const re = new RegExp(`\\b(${forms.join("|")})\\b`, "gi");
		return esc(text).replace(re, '<span class="blank" aria-label="blank"></span>');
	}

	// Letter-by-letter alignment so we can underline what was missed.
	function diffMarks(typed, word) {
		const t = typed, w = word;
		const d = Array.from({ length: t.length + 1 }, () => new Array(w.length + 1).fill(0));
		for (let i = 0; i <= t.length; i++) d[i][0] = i;
		for (let j = 0; j <= w.length; j++) d[0][j] = j;
		for (let i = 1; i <= t.length; i++) {
			for (let j = 1; j <= w.length; j++) {
				d[i][j] = Math.min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + (t[i - 1] === w[j - 1] ? 0 : 1));
			}
		}
		const ok = new Array(w.length).fill(false);
		let i = t.length, j = w.length;
		while (i > 0 && j > 0) {
			if (t[i - 1] === w[j - 1] && d[i][j] === d[i - 1][j - 1]) { ok[j - 1] = true; i--; j--; }
			else if (d[i][j] === d[i - 1][j - 1] + 1) { i--; j--; }
			else if (d[i][j] === d[i - 1][j] + 1) { i--; }
			else { j--; }
		}
		return w.split("").map((ch, k) => ok[k] ? esc(ch) : `<span class="miss">${esc(ch)}</span>`).join("");
	}

	const spelledOut = word => word.toUpperCase().split("").join(", ");

	function spellItOut(word) {
		return Widgets.speakButton({ label: "Hear it spelled", text: `${word}. ${spelledOut(word)}. ${word}.`, rate: 0.75 });
	}

	/* ---------- One word ---------- */

	function render({ entry }, area, ui) {
		const clue = (label, html) => Widgets.el(
			`<div class="clue"><span class="clue-label">${esc(label)}</span>${html}</div>`);
		const sentence = clue("Sentence", masked(entry.s, entry));
		const meaning = entry.d ? clue(entry.p ? `Meaning · ${entry.p}` : "Meaning", masked(entry.d, entry)) : null;
		const { form, input } = Widgets.answerForm({
			placeholder: "Type the word here", label: "Your spelling", onSubmit: check
		});
		const focus = () => Widgets.focus(input);

		const row = Widgets.el(`<div class="clue-row"></div>`);
		row.append(
			Widgets.speakButton({ label: "Slower", icon: "ph-turtle", text: entry.w, rate: 0.5, after: focus }),
			Widgets.speakButton({ label: "Use it in a sentence", icon: "ph-chat-text", text: entry.s,
				after: () => { sentence.classList.add("show"); focus(); } }));
		if (meaning) {
			row.append(Widgets.speakButton({ label: "Meaning", icon: "ph-book-open", text: entry.d,
				after: () => { meaning.classList.add("show"); focus(); } }));
		}

		area.append(
			Widgets.speakButton({ label: "Hear the word", text: entry.w, rate: 0.8, big: true, after: focus }),
			row);
		if (entry.h) {
			area.append(Widgets.el(`<p class="sound-alike"><i class="ph-bold ph-warning"></i>
				This word sounds like another word. Use the sentence or meaning to be sure which one.</p>`));
		}
		area.append(sentence);
		if (meaning) area.append(meaning);
		area.append(form);
		focus();

		// Short pause so the card is on screen before the voice starts.
		setTimeout(() => { if (!ui.answered()) Speech.say(entry.w, { rate: 0.8 }); }, 250);

		function check(value) {
			const typed = norm(value);
			if (typed === entry.w) {
				input.classList.add("field-correct");
				return ui.correct();
			}
			// A real word that sounds the same isn't a spelling mistake, so
			// don't punish it; point them at the clues instead.
			if ((entry.h || []).includes(typed)) {
				sentence.classList.add("show");
				if (meaning) meaning.classList.add("show");
				input.select();
				return ui.tryAgain("That's a different word that sounds the same. Try the sentence or meaning.");
			}
			input.classList.add("field-wrong");
			ui.wrong({
				typed,
				answer: `<span class="mono">${diffMarks(typed, entry.w)}</span>`,
				note: (entry.a || []).includes(typed)
					? `“${esc(typed)}” is the American spelling. In NZ English it's “${esc(entry.w)}”.`
					: null,
				actions: [spellItOut(entry.w)]
			});
		}
	}

	LevelGame.create({
		mount: "game",
		recordsEl: "records",
		storageKey: "spelling-bee-v1",
		noun: ["word", "words"],
		levels: LEVELS,
		needsSpeech: true,
		remember: true,
		tip: "Press Enter to check.",
		prepare: loadLevel,
		next,
		render,
		explain: ({ entry }) => ({ answer: `<span class="mono">${esc(entry.w)}</span>`, actions: [spellItOut(entry.w)] }),
		reviewItem: ({ entry }, typed) => ({ label: entry.w, typed, say: entry.w })
	});
})();
