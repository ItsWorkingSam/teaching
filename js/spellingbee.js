/* ============================================================
   Spelling Bee engine.
   Word packs live in js/bee-words/level-N.js (generated by
   tools/build_bee_words.py) and are loaded one level at a time.
   Each word: { w, p?, d?, s, a?, h? }
     w word · p part of speech · d definition · s example sentence
     a accepted US spellings · h sound-alike words
   Depends on training-core.js (Speech, showToast, Store, theme).
   ============================================================ */

(function () {
	const LEVELS = [
		{ name: "Starter", blurb: "Short, everyday words" },
		{ name: "Everyday", blurb: "Common words you read often" },
		{ name: "Confident", blurb: "Longer words and patterns" },
		{ name: "Tricky", blurb: "Silent letters, doubles and more" },
		{ name: "Advanced", blurb: "Longer, less common words" },
		{ name: "Expert", blurb: "Hard words for strong spellers" },
		{ name: "Champion", blurb: "The toughest words in the bee" }
	];
	const TO_LEVEL_UP = 5;      // correct new words needed to move up
	const LIVES = 3;
	const REVIEW_GAP = 4;       // a missed word comes back after this many others
	const MISSES_TO_DROP = 3;   // practice mode: misses in a row before easing off
	const MASTERED_CAP = 5000;
	const STATS_KEY = "spelling-bee-v1";
	const PRAISE = ["Correct!", "Nice work!", "Perfect!", "Well spelled!", "That's it!", "Excellent!"];

	const $ = id => document.getElementById(id);

	let stats = Store.getJSON(STATS_KEY, {});
	stats = Object.assign({ words: 0, correct: 0, bestStreak: 0, highestLevel: 0, lastLevel: 1, lastMode: "practice", mastered: [] }, stats);
	const mastered = new Set(stats.mastered);

	let chosenLevel = Math.min(Math.max(stats.lastLevel, 1), LEVELS.length);
	let chosenMode = stats.lastMode === "challenge" ? "challenge" : "practice";

	let game = null;

	/* ---------- Word packs ---------- */

	const packs = {};
	function loadLevel(n) {
		window.BEE_WORDS = window.BEE_WORDS || {};
		if (window.BEE_WORDS[n]) return Promise.resolve(window.BEE_WORDS[n]);
		if (!packs[n]) {
			// A script tag rather than fetch() so the page also works when
			// opened straight from disk (file://).
			packs[n] = new Promise((resolve, reject) => {
				const s = document.createElement("script");
				s.src = `./js/bee-words/level-${n}.js`;
				s.onload = () => window.BEE_WORDS[n] ? resolve(window.BEE_WORDS[n]) : reject(new Error("empty pack"));
				s.onerror = () => { delete packs[n]; reject(new Error("load failed")); };
				document.head.appendChild(s);
			});
		}
		return packs[n];
	}

	/* ---------- Helpers ---------- */

	function esc(s) {
		return String(s == null ? "" : s)
			.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
	}

	function norm(s) {
		return (s || "").trim().toLowerCase().replace(/[‘’]/g, "'").replace(/\s+/g, " ");
	}

	// Hide the answer (and its US spelling) wherever it appears in a clue.
	function masked(text, entry) {
		const forms = [entry.w].concat(entry.a || []);
		const re = new RegExp(`\\b(${forms.join("|")})\\b`, "gi");
		return esc(text).replace(re, '<span class="blank" aria-label="blank"></span>');
	}

	// Letter-by-letter alignment so we can underline what was missed.
	function diffMarks(typed, word) {
		const t = typed, w = word;
		const d = Array.from({ length: t.length + 1 }, () => new Array(w.length + 1).fill(0));
		for (let i = 0; i <= t.length; i++) d[i][0] = i;
		for (let j = 0; j <= w.length; j++) d[0][j] = j;
		for (let i = 1; i <= t.length; i++) {
			for (let j = 1; j <= w.length; j++) {
				d[i][j] = Math.min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + (t[i - 1] === w[j - 1] ? 0 : 1));
			}
		}
		const ok = new Array(w.length).fill(false);
		let i = t.length, j = w.length;
		while (i > 0 && j > 0) {
			if (t[i - 1] === w[j - 1] && d[i][j] === d[i - 1][j - 1]) { ok[j - 1] = true; i--; j--; }
			else if (d[i][j] === d[i - 1][j - 1] + 1) { i--; j--; }
			else if (d[i][j] === d[i - 1][j] + 1) { i--; }
			else { j--; }
		}
		return w.split("").map((ch, k) => ok[k] ? esc(ch) : `<span class="miss">${esc(ch)}</span>`).join("");
	}

	function spelledOut(word) {
		return word.toUpperCase().split("").join(", ");
	}

	function saveStats() {
		stats.mastered = Array.from(mastered).slice(-MASTERED_CAP);
		Store.setJSON(STATS_KEY, stats);
	}

	/* ---------- Start screen ---------- */

	function renderStart() {
		$("level-grid").innerHTML = LEVELS.map((l, i) => `
			<button class="level-btn" data-level="${i + 1}" aria-pressed="${i + 1 === chosenLevel}">
				<span class="lvl-num">Level ${i + 1}</span>
				<span class="lvl-name">${l.name}</span>
				<span class="lvl-eg">${l.blurb}</span>
			</button>`).join("");

		$("level-grid").querySelectorAll("[data-level]").forEach(b => {
			b.addEventListener("click", () => {
				chosenLevel = +b.dataset.level;
				$("level-grid").querySelectorAll("[data-level]").forEach(x =>
					x.setAttribute("aria-pressed", String(x === b)));
				loadLevel(chosenLevel).catch(() => {});   // warm it up
			});
		});

		document.querySelectorAll("[data-mode]").forEach(b => {
			b.setAttribute("aria-pressed", String(b.dataset.mode === chosenMode));
			b.onclick = () => {
				chosenMode = b.dataset.mode;
				document.querySelectorAll("[data-mode]").forEach(x =>
					x.setAttribute("aria-pressed", String(x === b)));
			};
		});

		renderRecords();
		checkSpeech();
		loadLevel(chosenLevel).catch(() => {});
	}

	function renderRecords() {
		const el = $("records");
		if (!stats.words) { el.innerHTML = ""; return; }
		const pct = Math.round((stats.correct / stats.words) * 100);
		el.innerHTML = `
			<span class="hint-title" style="margin-bottom:6px;"><i class="ph-bold ph-trophy"></i> Your records</span>
			<div><span>Words spelled</span><b>${stats.words}</b></div>
			<div><span>Accuracy</span><b>${pct}%</b></div>
			<div><span>Best streak</span><b>${stats.bestStreak}</b></div>
			<div><span>Highest level</span><b>${stats.highestLevel || "-"}</b></div>`;
	}

	function checkSpeech() {
		const warn = $("speech-warning");
		const show = msg => { warn.textContent = msg; warn.style.display = "block"; };
		if (!Speech.supported()) {
			show("This browser can't read words out loud, so the Spelling Bee won't work here. Try Chrome, Edge or Safari.");
			return;
		}
		// Voices load late in some browsers; give them a moment.
		setTimeout(() => {
			if (!window.speechSynthesis.getVoices().length) {
				show("No text-to-speech voices were found. Check your device's speech settings, or try another browser.");
			}
		}, 2000);
	}

	/* ---------- Game flow ---------- */

	async function startGame() {
		stats.lastLevel = chosenLevel;
		stats.lastMode = chosenMode;
		saveStats();

		game = {
			mode: chosenMode,
			startLevel: chosenLevel,
			level: chosenLevel,
			inLevel: 0,
			done: 0,
			correct: 0,
			streak: 0,
			bestStreak: 0,
			lives: LIVES,
			missStreak: 0,
			used: new Set(),
			review: [],          // { entry, due, tries }
			missed: new Map(),   // word -> last thing typed
			current: null,
			answered: false
		};

		$("start-screen").classList.remove("active");
		$("success-screen").style.display = "none";
		$("game-screen").classList.add("active");
		$("word-area").innerHTML = `<p class="loading"><i class="ph-bold ph-spinner"></i> Loading words…</p>`;
		renderTop();

		try {
			await loadLevel(game.level);
		} catch (e) {
			$("word-area").innerHTML = `<p class="loading">Sorry, the word list couldn't be loaded. Check your connection and refresh the page.</p>`;
			return;
		}
		if (game.level < LEVELS.length) loadLevel(game.level + 1).catch(() => {});
		nextWord();
	}

	function renderTop() {
		$("level-label").textContent = `Level ${game.level} · ${LEVELS[game.level - 1].name}`;
		const filled = game.level === LEVELS.length ? TO_LEVEL_UP : game.inLevel;
		$("level-dots").innerHTML = Array.from({ length: TO_LEVEL_UP }, (_, i) =>
			`<span class="${i < filled ? "on" : ""}"></span>`).join("");
		$("lives").innerHTML = game.mode === "challenge"
			? Array.from({ length: LIVES }, (_, i) =>
				`<i class="ph-bold ph-heart${i < game.lives ? "" : " lost"}"></i>`).join("")
			: "";
		$("lives").setAttribute("aria-label", `${game.lives} lives left`);
		$("stat-done").textContent = game.done;
		$("stat-correct").textContent = game.correct;
		$("stat-streak").textContent = game.streak;
	}

	/* Words in each pack run easiest to hardest. Progress through a level
	   slides a window along the pack, so the words get harder within a
	   level as well as between levels. */
	function pickWord() {
		const due = game.review.findIndex(r => r.due <= game.done);
		if (due !== -1) {
			const r = game.review.splice(due, 1)[0];
			return { entry: r.entry, review: true, tries: r.tries };
		}

		const list = window.BEE_WORDS[game.level];
		const n = list.length;
		const size = Math.ceil(n / TO_LEVEL_UP);
		const step = Math.min(game.inLevel, TO_LEVEL_UP - 1);
		const start = Math.floor((step / TO_LEVEL_UP) * n);
		const windowed = list.slice(start, start + size);

		const fresh = e => !game.used.has(e.w);
		let pool = windowed.filter(e => fresh(e) && !mastered.has(e.w));
		if (!pool.length) pool = list.filter(e => fresh(e) && !mastered.has(e.w));
		if (!pool.length) pool = list.filter(fresh);
		if (!pool.length) {           // spelled the whole level this session
			list.forEach(e => game.used.delete(e.w));
			pool = windowed;
		}
		const entry = pool[Math.floor(Math.random() * pool.length)];
		return { entry, review: false, tries: 0 };
	}

	function nextWord() {
		if (game.mode === "challenge" && game.lives <= 0) { finish(); return; }

		game.current = pickWord();
		game.answered = false;
		game.used.add(game.current.entry.w);
		renderWord();
		renderTop();
		sayWord();
	}

	function renderWord() {
		const { entry, review } = game.current;
		const meaningBtn = entry.d
			? `<button class="speak-btn small" id="meaning-btn"><i class="ph-bold ph-book-open"></i> Meaning</button>`
			: "";
		const soundAlike = entry.h
			? `<p class="sound-alike"><i class="ph-bold ph-warning"></i> This word sounds like another word. Use the sentence or meaning to be sure which one.</p>`
			: "";
		const label = entry.p ? `Meaning · ${esc(entry.p)}` : "Meaning";

		$("word-area").innerHTML = `
			${review ? `<p class="review-tag"><i class="ph-bold ph-arrow-counter-clockwise"></i> Second chance</p>` : ""}
			<button class="btn hear-main" id="hear-btn"><i class="ph-bold ph-speaker-high"></i> Hear the word</button>
			<div class="clue-row">
				<button class="speak-btn small" id="slow-btn"><i class="ph-bold ph-turtle"></i> Slower</button>
				<button class="speak-btn small" id="sentence-btn"><i class="ph-bold ph-chat-text"></i> Use it in a sentence</button>
				${meaningBtn}
			</div>
			${soundAlike}
			<div class="clue" id="sentence-clue"><span class="clue-label">Sentence</span>${masked(entry.s, entry)}</div>
			<div class="clue" id="meaning-clue"><span class="clue-label">${label}</span>${entry.d ? masked(entry.d, entry) : ""}</div>

			<form class="answer-row" id="answer-form" autocomplete="off">
				<label for="answer" class="sr-only">Your spelling</label>
				<input type="text" id="answer" placeholder="Type the word here"
					autocomplete="off" autocorrect="off" autocapitalize="none" spellcheck="false" enterkeyhint="done">
				<button class="btn" type="submit" id="check-btn"><i class="ph-bold ph-check"></i>&nbsp; Check</button>
			</form>
			<div class="under-row">
				<span class="mini-note" style="margin:0;">Press Enter to check.</span>
				<span>
					<button class="text-btn" id="skip-btn"><i class="ph-bold ph-question"></i> I don't know</button>
					<button class="text-btn" id="finish-btn"><i class="ph-bold ph-flag-checkered"></i> Finish</button>
				</span>
			</div>
			<div class="result" id="result" role="status"></div>`;

		const speakFrom = (btn, text, rate) => {
			if (!Speech.supported()) { showToast("Speech isn't available in this browser", "info", 1600); return; }
			btn.classList.add("speaking");
			Speech.say(text, { rate, onend: () => btn.classList.remove("speaking") });
		};

		$("hear-btn").addEventListener("click", e => { speakFrom(e.currentTarget, entry.w, 0.8); focusAnswer(); });
		$("slow-btn").addEventListener("click", e => { speakFrom(e.currentTarget, entry.w, 0.5); focusAnswer(); });
		$("sentence-btn").addEventListener("click", e => {
			$("sentence-clue").classList.add("show");
			speakFrom(e.currentTarget, entry.s, 0.85);
			focusAnswer();
		});
		if (entry.d) {
			$("meaning-btn").addEventListener("click", e => {
				$("meaning-clue").classList.add("show");
				speakFrom(e.currentTarget, entry.d, 0.85);
				focusAnswer();
			});
		}

		$("answer-form").addEventListener("submit", e => { e.preventDefault(); check(); });
		$("answer").addEventListener("input", () => $("answer").classList.remove("field-wrong"));
		$("skip-btn").addEventListener("click", () => { if (!game.answered) wrong(""); });
		$("finish-btn").addEventListener("click", finish);
		focusAnswer();
	}

	function focusAnswer() {
		const input = $("answer");
		if (input && !input.disabled) input.focus();
	}

	function sayWord() {
		// Small delay so the new card is on screen before the voice starts.
		setTimeout(() => {
			if (game && game.current && !game.answered) Speech.say(game.current.entry.w, { rate: 0.8 });
		}, 250);
	}

	/* ---------- Checking ---------- */

	function check() {
		if (game.answered) return;
		const entry = game.current.entry;
		const typed = norm($("answer").value);

		if (!typed) { showToast("Type the word first", "info", 1300); return; }

		if (typed === entry.w) return right();
		if ((entry.a || []).includes(typed)) return right(`Correct! In NZ English it's usually spelled “${entry.w}”.`);

		// A real word that sounds the same isn't a spelling mistake, so
		// don't punish it; point them at the clues instead.
		if ((entry.h || []).includes(typed)) {
			showToast("That's a different word that sounds the same. Try the sentence or meaning.", "info", 2600);
			$("sentence-clue").classList.add("show");
			if (entry.d) $("meaning-clue").classList.add("show");
			$("answer").select();
			return;
		}

		wrong(typed);
	}

	function lockInput() {
		game.answered = true;
		$("answer").disabled = true;
		$("check-btn").disabled = true;
		$("skip-btn").disabled = true;
	}

	function right(message) {
		lockInput();
		const { entry, review } = game.current;
		$("answer").classList.add("field-correct");

		game.done++; game.correct++; game.streak++;
		game.bestStreak = Math.max(game.bestStreak, game.streak);
		game.missStreak = 0;
		stats.words++; stats.correct++;
		stats.bestStreak = Math.max(stats.bestStreak, game.streak);
		stats.highestLevel = Math.max(stats.highestLevel, game.level);
		if (!review) mastered.add(entry.w);
		saveStats();

		showToast(message || PRAISE[game.correct % PRAISE.length], "success", message ? 2200 : 1000);

		let levelledUp = false;
		if (!review) {
			game.inLevel++;
			if (game.inLevel >= TO_LEVEL_UP && game.level < LEVELS.length) {
				game.level++;
				game.inLevel = 0;
				levelledUp = true;
				stats.highestLevel = Math.max(stats.highestLevel, game.level);
				saveStats();
			}
		}
		renderTop();

		setTimeout(async () => {
			if (levelledUp) {
				showToast(`Level up! Level ${game.level}: ${LEVELS[game.level - 1].name}`, "success", 2000);
				if (!(await ensureLevel())) return;
			}
			nextWord();
		}, message ? 1800 : 1000);
	}

	function wrong(typed) {
		lockInput();
		const { entry, review, tries } = game.current;
		$("answer").classList.add("field-wrong");

		game.done++;
		game.streak = 0;
		game.missStreak++;
		game.missed.set(entry.w, typed);
		stats.words++;
		saveStats();

		if (tries < 1) {
			game.review.push({ entry, due: game.done + REVIEW_GAP, tries: tries + 1 });
		}

		let note = "";
		if (game.mode === "challenge") {
			game.lives--;
			note = game.lives > 0
				? `${game.lives} ${game.lives === 1 ? "life" : "lives"} left.`
				: "That was your last life.";
		} else if (game.missStreak >= MISSES_TO_DROP && game.level > 1) {
			game.level--;
			game.inLevel = 0;
			game.missStreak = 0;
			note = `Let's try some slightly easier words for a bit (Level ${game.level}).`;
		} else if (!review) {
			note = "It'll come back again soon for another try.";
		}
		renderTop();

		const typedLine = typed
			? `<p class="spell-line">You wrote</p><div class="word-big typed">${esc(typed)}</div>`
			: "";
		const result = $("result");
		result.innerHTML = `
			<p class="result-title"><i class="ph-bold ph-x-circle" style="color:var(--error)"></i> ${typed ? "Not quite" : "Here's the word"}</p>
			${typedLine}
			<p class="spell-line">Correct spelling</p>
			<div class="word-big">${typed ? diffMarks(typed, entry.w) : esc(entry.w)}</div>
			${note ? `<p class="spell-line" style="margin-top:10px;">${esc(note)}</p>` : ""}
			<div class="btn-row" style="margin-top:12px;">
				<button class="btn" id="next-btn"><i class="ph-bold ph-arrow-right"></i>&nbsp; ${game.mode === "challenge" && game.lives <= 0 ? "See results" : "Next word"}</button>
				<button class="speak-btn small" id="spell-btn"><i class="ph-bold ph-speaker-high"></i> Hear it spelled</button>
			</div>`;
		result.classList.add("show");

		$("spell-btn").addEventListener("click", e => {
			const btn = e.currentTarget;
			btn.classList.add("speaking");
			Speech.say(`${entry.w}. ${spelledOut(entry.w)}. ${entry.w}.`, { rate: 0.75, onend: () => btn.classList.remove("speaking") });
		});
		$("next-btn").addEventListener("click", async () => {
			if (!(await ensureLevel())) return;
			nextWord();
		});
		$("next-btn").focus();
	}

	// The level may have changed; make sure its words are loaded.
	async function ensureLevel() {
		try {
			await loadLevel(game.level);
			if (game.level < LEVELS.length) loadLevel(game.level + 1).catch(() => {});
			return true;
		} catch (e) {
			showToast("Couldn't load the next words. Check your connection.", "error", 2600);
			return false;
		}
	}

	/* ---------- Summary ---------- */

	function finish() {
		if (!game) return;
		if (window.speechSynthesis) window.speechSynthesis.cancel();
		$("game-screen").classList.remove("active");

		if (!game.done) {         // nothing attempted: straight back to the menu
			game = null;
			showStart();
			return;
		}

		const pct = Math.round((game.correct / game.done) * 100);
		const out = game.mode === "challenge" && game.lives <= 0;
		$("summary-emoji").textContent = pct >= 80 ? "🏆" : "🐝";
		$("summary-title").textContent = out ? "Out of lives" : "Well done!";
		const climbed = game.level - game.startLevel;
		$("summary-note").textContent = climbed > 0
			? `You climbed ${climbed} ${climbed === 1 ? "level" : "levels"}, from Level ${game.startLevel} to Level ${game.level}.`
			: `You finished on Level ${game.level} · ${LEVELS[game.level - 1].name}.`;

		const tile = (value, label) => `<div class="stat"><b>${value}</b><span>${label}</span></div>`;
		$("summary-stats").innerHTML =
			tile(game.done, "Words") + tile(game.correct, "Correct") +
			tile(pct + "%", "Accuracy") + tile(game.bestStreak, "Best streak");

		const missed = Array.from(game.missed.entries());
		$("summary-review").innerHTML = missed.length ? `
			<p class="section-label" style="text-align:left;margin-top:8px;">Words to practise</p>
			<ul class="review-list">
				${missed.map(([w, t]) => `
					<li>
						<span><span class="rw">${esc(w)}</span>${t && t !== w ? `<span class="rt">${esc(t)}</span>` : ""}</span>
						<button class="speak-btn small" data-say="${esc(w)}" aria-label="Hear ${esc(w)}"><i class="ph-bold ph-speaker-high"></i></button>
					</li>`).join("")}
			</ul>` : "";
		$("summary-review").querySelectorAll("[data-say]").forEach(b =>
			b.addEventListener("click", () => Speech.say(b.dataset.say, { rate: 0.8 })));

		$("success-screen").style.display = "block";
		renderRecords();
	}

	function showStart() {
		$("success-screen").style.display = "none";
		$("game-screen").classList.remove("active");
		$("start-screen").classList.add("active");
		renderStart();
	}

	/* ---------- Start ---------- */

	function init() {
		renderStart();
		$("start-btn").addEventListener("click", startGame);
		$("again-btn").addEventListener("click", () => { game = null; showStart(); });
	}

	if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init);
	else init();
})();
